#include "../includes/push_swap.h"

int	is_empty(char *str)
{
	int	i;

	i = 0;
	while ((str[i] >= 9 && str[i] <= 12) || str[i] == 32)
		i++;
	if (!str[i])
		return (1);
	return (0);
}
